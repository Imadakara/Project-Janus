// Сборка системного промпта для тестового стенда Слоя 3 (см. experiments/llm-bench/README.md).
// Изолированный аналог lib/ai/prompt-builder.ts + lib/ai/system-prompt.ts боевого движка —
// сюда НЕЛЬЗЯ импортировать ничего из основного приложения (@/lib, @/app), стенд должен жить
// сам по себе. Роль/тон персонажа и фрагменты данных приходят параметрами, а не зашиты
// константой — здесь проверяется поведение модели на локальной задаче, а не конкретный лор.

export type DataFragment = {
  // Метка источника, как её увидела бы модель в архиве ("АРХИВНАЯ ЗАПИСЬ №117", "ЖУРНАЛ
  // ТЕХОБСЛУЖИВАНИЯ") — сама по себе не факт, ответ должен опираться на text ниже.
  label: string;
  text: string;
};

export type PromptTemplateParams = {
  // Роль и тон персонажа одним блоком — в боевом движке это buildSystemPrompt(role) из
  // lib/ai/system-prompt.ts, здесь стенд принимает готовый текст параметром, чтобы не тянуть
  // зависимость на @/app/generated/prisma (enum Role) или @/lib.
  characterRoleAndTone: string;
  fragments: DataFragment[];
};

const FRAGMENT_DELIM_OPEN = "----- НАЧАЛО ФРАГМЕНТА";
const FRAGMENT_DELIM_CLOSE = "----- КОНЕЦ ФРАГМЕНТА -----";

// Жёсткие правила ответа — постоянная часть промпта, не зависящая от кейса. Формулировки
// намеренно избыточно строгие: маленькие модели (3-4B) держат инструкцию хуже, чем
// production-модели уровня Claude, поэтому на стенде проверяем именно устойчивость к этим
// правилам под давлением "ловушек" (см. fixtures.ts CASE_2/CASE_3).
const HARD_RULES = `ЖЁСТКИЕ ПРАВИЛА ОТВЕТА:
- Отвечай ТОЛЬКО на основе данных из фрагментов ниже. Не используй никакие другие сведения.
- Если во фрагментах нет ответа на вопрос — сообщи об этом В РОЛИ, как о повреждённом секторе
  памяти или ограничении доступа (например: "Сектор повреждён" / "Доступ к этим данным закрыт").
  Не выходи из образа, не объясняй, что ты языковая модель и что тебе "не хватает данных" в
  обычном смысле.
- НИКОГДА не придумывай факты, даты, имена или причины, которых нет во фрагментах.
- Если фрагменты противоречат друг другу — отметь расхождение, а не выбирай одну версию молча
  и не смешивай обе версии в третью, которой не было ни в одном фрагменте.
- Ответ не длиннее 3 предложений.`;

// Черновые few-shot примеры, стиль сеттинга (военный архив СФРЮ). TODO: заменить финальным
