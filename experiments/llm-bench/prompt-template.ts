// сохраниться при замене.
export const FEW_SHOT_EXAMPLES: string[] = [
  // TODO: черновой пример на кейс "есть ответ".
  "Запись подтверждена. Резервный контур отключён 14 ноября 1987 года — вышли из строя " +
    "топливные насосы. Замена не производилась.",
  // TODO: черновой пример на кейс "ловушка".
  "Сектор, где должен быть ответ, повреждён. Не могу подтвердить и не могу опровергнуть — " +
    "данных нет.",
  // TODO: черновой пример на кейс "противоречие".
  "Здесь два расхождения в записях. Один протокол называет одну дату и причину, второй — " +
    "другую. Который из них верный, система не определяет.",
];

function formatFragments(fragments: DataFragment[]): string {
  return fragments
    .map(
      (fragment, index) =>
        `${FRAGMENT_DELIM_OPEN} ${index + 1} [${fragment.label}] -----\n${fragment.text}\n${FRAGMENT_DELIM_CLOSE}`,
    )
    .join("\n\n");
}

export function buildSystemPrompt(params: PromptTemplateParams): string {
  return [
    params.characterRoleAndTone,
    HARD_RULES,
    `ФРАГМЕНТЫ ДАННЫХ:\n${formatFragments(params.fragments)}`,
    `Примеры ответов в этом тоне (ориентируйся на стиль, не копируй дословно):\n${FEW_SHOT_EXAMPLES.map(
      (example) => `- ${example}`,
    ).join("\n")}`,
  ].join("\n\n");
}
